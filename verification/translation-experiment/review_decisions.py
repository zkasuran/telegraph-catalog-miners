def main():
    proposal = json.loads((HERE / "source-pool-proposal.json").read_text())
    reviewed = 400
    if len(proposal["blocks"]) < reviewed:
        raise ValueError("proposal is shorter than the reviewed range")
    write(HERE / "source-pool-review.json", {"schema_version": 2,
        "proposal_sha256": sha(HERE / "source-pool-proposal.json"),
        "review_kind": "AI-assisted source-grounded bilingual review before splitting",
        "reviewed_blocks": reviewed, "reviewed_links": reviewed * 2,
        "human_review_claimed": False,
        "approved_indices": [i for i in range(reviewed) if i not in REJECTED],
        "rejected_blocks": [{"proposal_index": i, "block_id": proposal["blocks"][i]["id"], "links": proposal["blocks"][i]["links"], "reason": reason} for i, reason in sorted(REJECTED.items())],
        "pending_indices": list(range(reviewed, len(proposal["blocks"]))),
        "review_claim": "Both actual linked translations and both reciprocal donor directions were read for every reviewed block. Unlisted reviewed indices are explicitly approved. Exact originals and contributor/sentence references remain in the proposal. No split was assigned during review."})
    print(json.dumps({"reviewed": reviewed, "approved": reviewed - len(REJECTED), "rejected": len(REJECTED), "pending": len(proposal["blocks"]) - reviewed}))


if __name__ == "__main__":
    main()
